#!/usr/bin/env node
// Self-contained daemon bundle (P5.M3.T2): aeos-<version>-<os>-<arch>.tar.gz
// holding aeosd + the aeos CLI (pnpm deploy — production node_modules only),
// the built web UI, AND the Node runtime that built it — so the only host
// requirement is git. Native modules (node-pty) are built for this platform,
// which is why CI runs this per OS/arch.
//
//   node scripts/release/bundle.mjs [outDir]      (after `pnpm build`)
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.resolve(process.argv[2] ?? path.join(ROOT, 'release-out'));
const version = JSON.parse(fs.readFileSync(path.join(ROOT, 'apps', 'aeosd', 'package.json'), 'utf8')).version;
const platform = `${process.platform === 'darwin' ? 'macos' : process.platform}-${process.arch}`;
const name = `aeos-${version}-${platform}`;
const stage = path.join(OUT, name);
fs.rmSync(stage, { recursive: true, force: true });
fs.mkdirSync(path.join(stage, 'bin'), { recursive: true });

const pnpm = (...args) => execFileSync('pnpm', args, { cwd: ROOT, stdio: 'inherit' });
pnpm('--filter', '@aeos/aeosd', 'deploy', '--prod', path.join(stage, 'lib', 'aeosd'));
pnpm('--filter', '@aeos/cli', 'deploy', '--prod', path.join(stage, 'lib', 'cli'));
fs.cpSync(path.join(ROOT, 'apps', 'ade', 'dist'), path.join(stage, 'lib', 'ui'), { recursive: true });

// the runtime this bundle was built and tested with
const nodeName = process.platform === 'win32' ? 'node.exe' : 'node';
fs.copyFileSync(process.execPath, path.join(stage, 'bin', nodeName));
fs.chmodSync(path.join(stage, 'bin', nodeName), 0o755);

const launcher = (entry, extraEnv = '') => `#!/bin/sh
# ${name} — generated by scripts/release/bundle.mjs
DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"
${extraEnv}exec "$DIR/node" "$DIR/../lib/${entry}" "$@"
`;
fs.writeFileSync(path.join(stage, 'bin', 'aeosd'), launcher('aeosd/dist/main.js', 'export AEOS_UI_DIR="${AEOS_UI_DIR:-$DIR/../lib/ui}"\n'), { mode: 0o755 });
fs.writeFileSync(
  path.join(stage, 'bin', 'aeos'),
  // AEOS_BUNDLE_DIR lets `aeos update` find the bundled installer (P5.M6.T3)
  launcher('cli/dist/main.js', 'export AEOS_BUNDLE_DIR="$(CDPATH= cd -- "$DIR/.." && pwd)"\n'),
  { mode: 0o755 },
);
// the verified installer, so `aeos update` re-runs exactly the install path
fs.copyFileSync(path.join(ROOT, 'scripts', 'install', 'install.sh'), path.join(stage, 'bin', 'aeos-install'));
fs.chmodSync(path.join(stage, 'bin', 'aeos-install'), 0o755);
fs.writeFileSync(
  path.join(stage, 'README.txt'),
  `AEOS ${version} (${platform})

  bin/aeosd run        start the daemon (web UI on http://127.0.0.1:7777)
  bin/aeos --help      the CLI

Requires git on PATH. State lives in ~/.aeos (override with AEOS_HOME).
Docs: https://mirrorfolio-idea-labs.github.io/AEOS/
`,
);
for (const f of ['LICENSE', 'THIRD_PARTY_NOTICES.md']) {
  if (fs.existsSync(path.join(ROOT, f))) fs.copyFileSync(path.join(ROOT, f), path.join(stage, f));
}

const tarball = path.join(OUT, `${name}.tar.gz`);
execFileSync('tar', ['-czf', tarball, '-C', OUT, name]);
fs.rmSync(stage, { recursive: true, force: true });
console.log(`bundle: ${path.relative(ROOT, tarball)} (${(fs.statSync(tarball).size / 1e6).toFixed(1)} MB)`);
